#!/usr/bin/env python3
"""Split DNS for the tunnel, driven by the "dns" section of settings.json.

Why this exists: a service can be reachable from the internet and from inside
the tunnel at the same time, and the public A record has to keep pointing at
the public address because machines out there depend on it. Clients inside the
tunnel need the internal address instead - otherwise their packets leave
through their own uplink and show up with the wrong source address, which is
what an IP allowlist on the far side rejects. A hosts file fixes that per
machine, but phones and tablets have none, so the answer has to come from the
server.

Three subcommands, because run.sh needs to tell "only DNS changed" (reload
dnsmasq, tunnel untouched) from "peers changed" (full wg-quick cycle):

    hash      md5 of the dns section
    resthash  md5 of everything except the dns section
    apply     write the dnsmasq config and reload it

The overrides go into a hosts file (addn-hosts), not into host-record= lines
of the config: SIGHUP makes dnsmasq re-read hosts files, but never its config.
With host-record= an edited override sat in the file and was not served until
dnsmasq was restarted by hand.
"""

import hashlib
import json
import os
import subprocess
import sys
import time
from pathlib import Path

SETTINGS = Path(os.environ.get("FILE_SETTINGS", "/root/settings/settings.json"))
CONF = Path("/etc/dnsmasq.d/vpn-overrides.conf")
# Outside the conf-dir, so dnsmasq never mistakes it for config.
HOSTS = Path("/etc/dnsmasq-vpn.hosts")
PIDFILE = Path("/run/dnsmasq-vpn.pid")


def _settings():
    try:
        return json.loads(SETTINGS.read_text())
    except (OSError, ValueError):
        # A missing or half-written settings.json must not take the tunnel
        # down - treat it as "nothing configured" and let the next reload fix
        # it. run.sh only calls us after the file changed, so a torn read here
        # is followed by another round anyway.
        return {}


def _dns_section():
    return _settings().get("dns") or {}


def _digest(obj):
    return hashlib.md5(
        json.dumps(obj, sort_keys=True).encode("utf-8")
    ).hexdigest()


def cmd_hash():
    print(_digest(_dns_section()))


def cmd_resthash():
    rest = {k: v for k, v in _settings().items() if k != "dns"}
    # create_date changes on every regeneration, so leaving it in would make
    # every DNS-only edit look like a peer change and cycle the tunnel.
    rest.pop("create_date", None)
    print(_digest(rest))


def _render(section):
    listen = (section.get("listen") or "").strip()
    upstream = (section.get("upstream") or "").strip()

    lines = [
        "# Generated by apply-dns.py from settings.json - do not edit.",
        "# Managed in Odoo: ovpn.site.wg_dns and ovpn.dns.record.",
        "",
        # The container runs with network_mode: host, so an unrestricted
        # dnsmasq would answer on the public address as well and hand the
        # internet an open resolver to amplify traffic with. listen-address
        # plus bind-dynamic keeps it on the tunnel address only, and
        # bind-dynamic (rather than bind-interfaces) is what survives wg1
        # disappearing during a peer reload.
        f"listen-address={listen}",
        "bind-dynamic",
        # Never forward names without a dot or reverse lookups for private
        # ranges upstream - they are noise at best and leak internal names at
        # worst.
        "domain-needed",
        "bogus-priv",
        "",
    ]

    if upstream:
        lines += ["no-resolv"]
        lines += [f"server={s.strip()}" for s in upstream.split(",") if s.strip()]
        lines += [""]

    lines.append(f"addn-hosts={HOSTS}")

    return "\n".join(lines) + "\n"


def _render_hosts(section):
    lines = ["# Generated by apply-dns.py from settings.json - do not edit."]
    for rec in section.get("records") or []:
        name = (rec.get("name") or "").strip()
        ip = (rec.get("ip") or "").strip()
        if not name or not ip:
            continue
        # A hosts entry matches the exact name only, like host-record did;
        # address=/name/ip would also capture every subdomain and silently
        # swallow names nobody asked us to override.
        lines.append(f"{ip} {name}")
    return "\n".join(lines) + "\n"


def _write(path, text):
    # Returns whether the content changed. Written via rename so that a
    # SIGHUP never catches dnsmasq reading a half-written file.
    try:
        if path.read_text() == text:
            return False
    except OSError:
        pass
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    tmp.replace(path)
    return True


def cmd_apply():
    section = _dns_section()
    listen = (section.get("listen") or "").strip()

    if not listen:
        # No resolver configured: make sure a previously written config does
        # not keep a stale dnsmasq alive.
        CONF.unlink(missing_ok=True)
        HOSTS.unlink(missing_ok=True)
        _stop()
        print("dns: no listen address configured - dnsmasq not running")
        return

    CONF.parent.mkdir(parents=True, exist_ok=True)
    _write(HOSTS, _render_hosts(section))
    if _write(CONF, _render(section)):
        # listen address or upstream changed: dnsmasq only picks that up on
        # a fresh start (DNS is gone for about a second, the tunnel is not
        # touched).
        _stop()
        _start()
    else:
        _reload()
    print(f"dns: {len(section.get('records') or [])} override(s) on {listen}")


def _pid():
    try:
        pid = int(PIDFILE.read_text().strip())
    except (OSError, ValueError):
        return None
    return pid if Path(f"/proc/{pid}").exists() else None


def _stop():
    pid = _pid()
    if pid:
        subprocess.call(["kill", str(pid)])
        # Wait until the old process has let go of port 53, otherwise the
        # new one fails to bind - and a failing apply ends run.sh (set -e),
        # which restarts the container and drops every peer.
        for _ in range(50):
            if not Path(f"/proc/{pid}").exists():
                break
            time.sleep(0.1)
    PIDFILE.unlink(missing_ok=True)


def _reload():
    pid = _pid()
    if pid:
        # SIGHUP makes dnsmasq re-read the hosts file without dropping its
        # socket, so clients see no gap.
        subprocess.call(["kill", "-HUP", str(pid)])
        return
    _start()


def _start():
    PIDFILE.unlink(missing_ok=True)
    subprocess.check_call(
        [
            "dnsmasq",
            "--conf-file=/dev/null",
            f"--conf-dir={CONF.parent},*.conf",
            f"--pid-file={PIDFILE}",
        ]
    )


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "apply"
    handler = {
        "hash": cmd_hash,
        "resthash": cmd_resthash,
        "apply": cmd_apply,
    }.get(cmd)
    if not handler:
        print(f"unknown command: {cmd}", file=sys.stderr)
        return 2
    handler()
    return 0


if __name__ == "__main__":
    sys.exit(main())
